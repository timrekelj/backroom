HEADER = """\
//! Generated by tools/gen_icons.py, do not edit.
//!
//! Phosphor Icons (@phosphor-icons/core {version}), {weight} weight, 256 grid.
//! Phosphor is MIT, Copyright (c) 2023 Phosphor Icons.
//! Licence text: LICENSES/phosphor-MIT.txt
use rune::Icon;
"""

COLOR = re.compile(r'\b(fill|stroke)="(?!none"|currentColor")[^"]*"')
SVG_OPEN = re.compile(r"<svg\b[^>]*>", re.S)


def ident(name):
    return name.replace("-", "_").upper()


def clean_body(inner):
    inner = re.sub(r"<!--.*?-->", "", inner, flags=re.S)
    inner = re.sub(r">\s+<", "><", inner.strip())
    inner = re.sub(r"\s+", " ", inner)
    inner = re.sub(r"\s*/>", "/>", inner)
    return COLOR.sub(lambda m: f'{m.group(1)}="currentColor"', inner)


def read_svg(path):
    """(view, inner markup) of a single-svg file, square viewBox required."""
    if not path.exists():
        raise SystemExit(f"missing in Phosphor: {path.name}")
    text = path.read_text(encoding="utf-8")
    m = SVG_OPEN.search(text)
    end = text.rfind("</svg>")
    if not m or end < 0:
        raise SystemExit(f"not an svg: {path}")
    vb = re.search(r'viewBox="([^"]+)"', m.group(0))
    x, y, w, h = (float(v) for v in vb.group(1).split())
    if (x, y) != (0.0, 0.0) or w != h:
        raise SystemExit(f"{path}: viewBox {vb.group(1)} is not a square at the origin")
    return w, text[m.end() : end]


def emit(path, weight, version, items):
    lines = [HEADER.format(weight=weight, version=version)]
    for name, view, body in items:
        assert '"##' not in body
        lines.append(
            f'pub static {ident(name)}: Icon = Icon {{ name: "{name}", view: {view:.1f}, body: r##"{body}"## }};'
        )
    lines.append("")
    lines.append("/// Every icon in this weight, in catalog order.")
    lines.append(f"pub static ALL: [&Icon; {len(items)}] = [")
    for name, _, _ in items:
        lines.append(f"    &{ident(name)},")
    lines.append("];")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


CATALOG_PARTS = 4

CATALOG_HEADER = """\
//! Generated by tools/gen_icons.py, do not edit.
//!
//! Phosphor Icons (@phosphor-icons/core {version}), {weight} weight: part {part} of the full catalog.
//! Phosphor is MIT, Copyright (c) 2023 Phosphor Icons. Licence text: LICENSES/phosphor-MIT.txt
use super::CatalogIcon;
use rune::Icon;
"""


def read_tags(index_mjs):
    """{name: [tags]} from dist/index.mjs, parsed as data (never executed)."""
    src = index_mjs.read_text(encoding="utf-8")
    out = {}
    for m in re.finditer(
        r'name:\s*"([a-z0-9-]+)"\s*,\s*pascal_name:.*?tags:\s*\[(.*?)\]', src, re.S
    ):
        tags = re.findall(r'"([^"]*)"', m.group(2))
        out[m.group(1)] = [t for t in tags if not t.startswith("*")]
    return out


def fill_path(phosphor, stem):
    return phosphor / "assets" / "fill" / f"{stem}-fill.svg"


def emit_catalog(out, phosphor, version):
    tags = read_tags(phosphor / "dist" / "index.mjs")
    stems = sorted(
        p.stem.removesuffix("-fill") for p in (phosphor / "assets" / "fill").glob("*-fill.svg")
    )
    assert stems, "no fill icons found"
    per = -(-len(stems) // CATALOG_PARTS)
    cat = out / "catalog"
    cat.mkdir(exist_ok=True)
    for old in cat.glob("part_*.rs"):
        old.unlink()
    for n in range(CATALOG_PARTS):
        lines = [CATALOG_HEADER.format(version=version, part=n + 1, weight="fill")]
        chunk = stems[n * per : (n + 1) * per]
        lines.append(f"pub static PART: [CatalogIcon; {len(chunk)}] = [")
        for stem in chunk:
            v, b = read_svg(fill_path(phosphor, stem))
            body = clean_body(b)
            assert '"##' not in body
            tg = ", ".join('"' + t.replace('"', "") + '"' for t in tags.get(stem, []))
            lines.append(
                f'    CatalogIcon {{ icon: Icon {{ name: "{stem}", view: {v:.1f}, body: r##"{body}"## }}, tags: &[{tg}] }},'
            )
        lines.append("];")
        (cat / f"part_{n}.rs").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(stems)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--phosphor", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    a = ap.parse_args()
    (a.out / "LICENSES").mkdir(parents=True, exist_ok=True)
    version = re.search(
        r'"version"\s*:\s*"([^"]+)"', (a.phosphor / "package.json").read_text()
    ).group(1)
    shutil.copyfile(a.phosphor / "LICENSE", a.out / "LICENSES" / "phosphor-MIT.txt")

    names = [n for n, _ in ICONS]
    assert len(set(names)) == len(names), "duplicate icon name"
    fill = []
    for ours, stem in ICONS:
        v, b = read_svg(fill_path(a.phosphor, stem))
        fill.append((ours, v, clean_body(b)))
    for old in ("regular.rs", "fill.rs"):
        (a.out / old).unlink(missing_ok=True)
    emit(a.out / "curated.rs", "fill", version, fill)
    total = emit_catalog(a.out, a.phosphor, version)
    print(
        f"wrote {len(ICONS)} fill icons and a {total}-icon catalog to {a.out} (phosphor {version})"
    )


if __name__ == "__main__":
    sys.exit(main())

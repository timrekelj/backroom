HEADER = """\
//! Generated by tools/gen_icons.py, do not edit.
//!
//! Phosphor Icons (@phosphor-icons/core {version}), {weight} weight, 256 grid.
//! Phosphor is MIT, Copyright (c) 2023 Phosphor Icons.
//! Licence text: LICENSES/phosphor-MIT.txt
use rune::Icon;
"""

COLOR = re.compile(r'\b(fill|stroke)="(?!none"|currentColor")[^"]*"')
SVG_OPEN = re.compile(r"<svg\b[^>]*>", re.S)


def ident(name):
    return name.replace("-", "_").upper()


def clean_body(inner):
    inner = re.sub(r"<!--.*?-->", "", inner, flags=re.S)
    inner = re.sub(r">\s+<", "><", inner.strip())
    inner = re.sub(r"\s+", " ", inner)
    inner = re.sub(r"\s*/>", "/>", inner)
    return COLOR.sub(lambda m: f'{m.group(1)}="currentColor"', inner)


def read_svg(path):
    """(view, inner markup) of a single-svg file, square viewBox required."""
    if not path.exists():
        raise SystemExit(f"missing in Phosphor: {path.name}")
    text = path.read_text(encoding="utf-8")
    m = SVG_OPEN.search(text)
    end = text.rfind("</svg>")
    if not m or end < 0:
        raise SystemExit(f"not an svg: {path}")
    vb = re.search(r'viewBox="([^"]+)"', m.group(0))
    x, y, w, h = (float(v) for v in vb.group(1).split())
    if (x, y) != (0.0, 0.0) or w != h:
        raise SystemExit(f"{path}: viewBox {vb.group(1)} is not a square at the origin")
    return w, text[m.end() : end]


def emit(path, weight, version, items):
    lines = [HEADER.format(weight=weight, version=version)]
    for name, view, body in items:
        assert '"##' not in body
        lines.append(
            f'pub static {ident(name)}: Icon = Icon {{ name: "{name}", view: {view:.1f}, body: r##"{body}"## }};'
        )
    lines.append("")
    lines.append("/// Every icon in this weight, in catalog order.")
    lines.append(f"pub static ALL: [&Icon; {len(items)}] = [")
    for name, _, _ in items:
        lines.append(f"    &{ident(name)},")
    lines.append("];")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--phosphor", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    a = ap.parse_args()
    (a.out / "LICENSES").mkdir(parents=True, exist_ok=True)
    version = re.search(
        r'"version"\s*:\s*"([^"]+)"', (a.phosphor / "package.json").read_text()
    ).group(1)
    shutil.copyfile(a.phosphor / "LICENSE", a.out / "LICENSES" / "phosphor-MIT.txt")

    names = [n for n, _ in ICONS]
    assert len(set(names)) == len(names), "duplicate icon name"
    regular, fill = [], []
    for ours, stem in ICONS:
        v, b = read_svg(a.phosphor / "assets" / "regular" / f"{stem}.svg")
        regular.append((ours, v, clean_body(b)))
        v, b = read_svg(a.phosphor / "assets" / "fill" / f"{stem}-fill.svg")
        fill.append((ours, v, clean_body(b)))
    emit(a.out / "regular.rs", "regular", version, regular)
    emit(a.out / "fill.rs", "fill", version, fill)
    print(f"wrote {len(ICONS)} icons x 2 weights to {a.out} (phosphor {version})")


if __name__ == "__main__":
    sys.exit(main())
